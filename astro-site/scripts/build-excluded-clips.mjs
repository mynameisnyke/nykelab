#!/usr/bin/env node
// Turns the library's duplicates.json (read-only) into excluded-clips.json, the one small file the loader filters on.
//   node scripts/build-excluded-clips.mjs [path/to/duplicates.json]
// Rule 1 (one subclip per source video) and rule 2 (same-looking first frame) are excluded by default;
// rule 2 was calculated among the survivors of rule 1. The borderline list is kept apart (publish-library.mjs --exclude-borderline).
import fs from "node:fs";

const src = process.argv[2] ?? "/Volumes/Whiskey/resolve/LibraryGrade/subclips/duplicates.json";
const d = JSON.parse(fs.readFileSync(src, "utf8"));
const r1 = d.rule_1_one_subclip_per_source_video;
const r2 = d.rule_2_same_looking_first_frame;
const bl = d.borderline_check_by_eye;
const dropped1 = new Set(r1.flatMap((g) => g.drop));
const stale = r2.map((g) => g.keep).filter((k) => dropped1.has(k));
if (stale.length) throw new Error(`rule 2 keeps dropped by rule 1: ${stale.join(", ")}`);

const keptFor = {}; // dropped id -> the clip that stays in its place
for (const g of [...r1, ...r2, ...bl]) for (const id of g.drop) keptFor[id] = g.keep;
const out = {
  note: "Clips hidden from the site (not deleted: files stay in storage). Generated by scripts/build-excluded-clips.mjs from the library's duplicates.json.",
  excluded: [...new Set([...r1, ...r2].flatMap((g) => g.drop))].sort(),
  borderline: [...new Set(bl.flatMap((g) => g.drop))].sort(),
  keptFor,
};
fs.writeFileSync(new URL("../excluded-clips.json", import.meta.url), JSON.stringify(out, null, 1) + "\n");
console.log(`excluded ${out.excluded.length}, borderline ${out.borderline.length}`);
