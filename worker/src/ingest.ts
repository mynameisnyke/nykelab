// Reads what a photo already says about itself (capture time, camera settings, caption, and where it was taken) so the
// admin does not have to type it. Runs in the Worker on the stored original; nothing here ever reaches the public API
// except city-level place names: the exact GPS fix is stored privately and never served.
//
// Location precedence: place text a human wrote in Lightroom (IPTC/XMP city, state, country) beats GPS; GPS becomes the
// nearest listed city; with neither, the place stays empty (the site falls back to the collection's place).
import exifr from "exifr";
import { countryCode, countryName, findCity, nearestCity } from "./places";

export interface PhotoMeta {
  /** Local wall-clock capture time, "2020-01-30T05:56:22" (no timezone: cameras do not record a reliable one). */
  capturedAt: string | null;
  camera: string;
  lens: string;
  focal: number | null;
  aperture: number | null;
  iso: number | null;
  shutter: string;
  /** Usable caption from the file's own tags ("" when it is camera junk or absent). */
  caption: string;
  /** "Medellín, Antioquia, Colombia" */
  place: string;
  city: string;
  region: string;
  country: string;
  countryCode: string;
  /** City-level coordinates of the place (public). */
  placeLat: number | null;
  placeLon: number | null;
  /** Where the place came from: "tags" (IPTC/XMP text), "gps" (nearest city) or "". */
  placeSource: "tags" | "gps" | "";
  /** Exact GPS fix. PRIVATE: stored for admin use, never returned by any API. */
  gpsLat: number | null;
  gpsLon: number | null;
}

export const EMPTY_META: PhotoMeta = {
  capturedAt: null,
  camera: "",
  lens: "",
  focal: null,
  aperture: null,
  iso: null,
  shutter: "",
  caption: "",
  place: "",
  city: "",
  region: "",
  country: "",
  countryCode: "",
  placeLat: null,
  placeLon: null,
  placeSource: "",
  gpsLat: null,
  gpsLon: null,
};

/** EXIF/IPTC/XMP live in the first segments of a JPEG; this is plenty even with a large embedded preview. */
export const HEAD_BYTES = 512 * 1024;

type Raw = Record<string, unknown>;

const str = (v: unknown): string => {
  if (typeof v === "string") return v;
  if (v && typeof v === "object" && "value" in v && typeof (v as { value: unknown }).value === "string") return (v as { value: string }).value;
  return "";
};
const clean = (v: unknown) => str(v).replace(/\0/g, "").replace(/\s+/g, " ").trim();
const num = (v: unknown) => (typeof v === "number" && Number.isFinite(v) ? v : null);

// What cameras and editors write when nobody wrote a caption.
const JUNK_CAPTION =
  /^(sony dsc|olympus digital camera|nikon|canon|fujifilm|leica|dji|exif_?jpeg|untitled|processed with|screenshot|created with|generated by|img[_ -]?\d|_?dsc[_ -]?\d|dscf?\d|p\d{7}|\d+$)/i;

export function usableCaption(raw: string, camera: string): string {
  const c = raw.trim();
  if (c.length < 3 || !/\p{L}{2}/u.test(c)) return "";
  if (JUNK_CAPTION.test(c)) return "";
  const f = (s: string) => s.toLowerCase().replace(/\s+/g, " ");
  if (camera && (f(c) === f(camera) || f(camera).includes(f(c)) && c.length < 12)) return "";
  return c.slice(0, 2000);
}

function shutterOf(t: number | null) {
  if (!t || t <= 0) return "";
  return t < 1 ? `1/${Math.round(1 / t)}` : `${Math.round(t * 10) / 10}s`;
}

/** Pure: turn raw EXIF/IPTC/XMP fields into what the site stores. Exported for tests. */
export function metaFromRaw(r: Raw | null | undefined): PhotoMeta {
  if (!r) return { ...EMPTY_META };
  const make = clean(r.Make);
  const model = clean(r.Model);
  const camera = model && make && !model.toLowerCase().startsWith(make.toLowerCase()) ? `${make} ${model}` : model || make;

  const dt = clean(r.DateTimeOriginal);
  const m = /^(\d{4}):(\d\d):(\d\d) (\d\d):(\d\d):(\d\d)/.exec(dt);
  const capturedAt = m && m[1] !== "0000" ? `${m[1]}-${m[2]}-${m[3]}T${m[4]}:${m[5]}:${m[6]}` : null;

  const caption = usableCaption(clean(r.description) || clean(r.Caption) || clean(r.ImageDescription), camera);

  const lat = num(r.latitude);
  const lon = num(r.longitude);
  const hasGps = lat !== null && lon !== null && !(lat === 0 && lon === 0) && Math.abs(lat) <= 90 && Math.abs(lon) <= 180;

  const meta: PhotoMeta = {
    capturedAt,
    camera,
    lens: clean(r.LensModel),
    focal: num(r.FocalLength),
    aperture: num(r.FNumber),
    iso: num(r.ISO),
    shutter: shutterOf(num(r.ExposureTime)),
    caption,
    place: "",
    city: "",
    region: "",
    country: "",
    countryCode: "",
    placeLat: null,
    placeLon: null,
    placeSource: "",
    gpsLat: hasGps ? lat : null,
    gpsLon: hasGps ? lon : null,
  };

  // 1. Place text written in Lightroom (IPTC / XMP photoshop:City etc.)
  const tagCity = clean(r.City);
  const tagRegion = clean(r.State);
  const tagCountryRaw = clean(r.Country) || clean(r.CountryCode);
  const tagCc = countryCode(clean(r.CountryCode)) || countryCode(clean(r.Country));
  if (tagCity || tagRegion || tagCountryRaw) {
    const hit = tagCity ? findCity(tagCity, tagCc) : null;
    const country = (tagCc && countryName(tagCc)) || clean(r.Country) || "";
    meta.city = tagCity;
    meta.region = tagRegion || (hit && hit.countryCode === (tagCc || hit.countryCode) ? hit.region : "");
    meta.country = country;
    meta.countryCode = tagCc || hit?.countryCode || "";
    meta.placeLat = hit?.lat ?? null;
    meta.placeLon = hit?.lon ?? null;
    meta.placeSource = "tags";
  } else if (hasGps) {
    // 2. GPS -> nearest listed city (region + country only if the nearest city is far away)
    const n = nearestCity(lat!, lon!);
    if (n) {
      const near = n.km <= 40;
      meta.city = near ? n.city.name : "";
      meta.region = n.city.region;
      meta.country = n.city.country;
      meta.countryCode = n.city.countryCode;
      meta.placeLat = n.city.lat;
      meta.placeLon = n.city.lon;
      meta.placeSource = "gps";
    }
  }
  if (meta.placeSource) {
    const parts = [meta.city, meta.region, meta.country].filter(Boolean);
    meta.place = parts.filter((p, i) => i === 0 || p.toLowerCase() !== parts[i - 1].toLowerCase()).join(", ");
  }
  return meta;
}

/** Parse the head of an image file. Never throws: a file with no readable metadata yields empty meta. */
export async function parseMeta(head: ArrayBuffer | Uint8Array): Promise<PhotoMeta> {
  try {
    const raw = await exifr.parse(head, {
      tiff: true,
      exif: true,
      gps: true,
      iptc: true,
      xmp: true,
      icc: false,
      jfif: false,
      ihdr: false,
      mergeOutput: true,
      translateKeys: true,
      translateValues: true,
      reviveValues: false, // keep DateTimeOriginal as written (a Date would shift it by the server's timezone)
      sanitize: true,
      multiSegment: true,
    });
    return metaFromRaw(raw as Raw | null);
  } catch {
    return { ...EMPTY_META };
  }
}

/** Read the original from R2 (first HEAD_BYTES only) and parse it. JPEG carries metadata; other types return empty. */
export async function readMeta(bucket: R2Bucket, key: string): Promise<PhotoMeta> {
  if (!/\.(jpe?g|webp|png)$/i.test(key)) return { ...EMPTY_META };
  const obj = await bucket.get(key, { range: { offset: 0, length: HEAD_BYTES } });
  if (!obj) return { ...EMPTY_META };
  return parseMeta(await obj.arrayBuffer());
}
